  function resolveWebsiteLocale(preference) {
    if (preference && preference !== "auto" && SITE_I18N[preference]) {
      return preference;
    }
    const params = new URLSearchParams(globalScope.location ? globalScope.location.search : "");
    const qLang = params.get("lang");
    if (qLang && SITE_I18N[qLang]) return qLang;

    const nav = (globalScope.navigator && (globalScope.navigator.language || globalScope.navigator.userLanguage)) || "zh-CN";
    const lower = String(nav).toLowerCase().replace("_", "-");
    if (lower.startsWith("zh")) {
      return (lower.includes("tw") || lower.includes("hk") || lower.includes("hant") || lower.includes("mo"))
        ? "zh-TW"
        : "zh-CN";
    }
    if (lower.startsWith("ja")) return "ja";
    if (lower.startsWith("en")) return "en";
    return "en";
  }

  function formatReleaseDateForLocale(isoString, locale) {
    if (!isoString) return "";
    const d = new Date(isoString);
    if (Number.isNaN(d.getTime())) return String(isoString).slice(0, 10);
    const yyyy = d.getFullYear();
    const mm = String(d.getMonth() + 1).padStart(2, "0");
    const dd = String(d.getDate()).padStart(2, "0");
    if (locale === "en") {
      const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
      return `${months[d.getMonth()]} ${d.getDate()}, ${yyyy}`;
    }
    return `${yyyy}-${mm}-${dd}`;
  }

  function translateSite(locale, key, vars) {
    const dict = SITE_I18N[locale] || SITE_I18N["zh-CN"];
    let val = dict[key];
    if (val === undefined) val = SITE_I18N["zh-CN"][key];
    if (val === undefined) return key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        val = val.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return val;
  }

